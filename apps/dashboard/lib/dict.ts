export const dictionaries: Record<Lang, Dict> = { sw, en };

export function getDict(lang: Lang): Dict {
	return dictionaries[lang] ?? sw;
}

export function isLang(v: unknown): v is Lang {
	return v === "sw" || v === "en";
}

/** Picks the field for the current language, falling back to Swahili. */
export function pick(value: unknown, lang: Lang): string {
	if (typeof value === "string") return value;
	if (value && typeof value === "object") {
		const v = value as Record<string, string | undefined>;
		return (lang === "en" ? v.en || v.sw : v.sw || v.en) ?? "";
	}
	return "";
}

/** Normalises legacy English difficulty values to the curriculum's Swahili ones. */
export function difficultyKey(d: string | null | undefined): "mwanzilishi" | "wa kati" | "wa juu" {
	const v = (d ?? "").toLowerCase();
	if (v === "easy" || v === "beginner" || v === "mwanzilishi") return "mwanzilishi";
	if (v === "hard" || v === "advanced" || v === "wa juu") return "wa juu";
	return "wa kati";
}
