/** Host of the learners' app, shown on the projector ("nuruprogramming.org/sw/darasa"). */
export function playgroundUrl() {
	return (process.env.NEXT_PUBLIC_PLAYGROUND_URL || "https://nuruprogramming.org").replace(/\/$/, "");
}
